static std::string redText(const std::string& message) {
    return "\033[31m" + message + "\033[0m";
}

// Runs a shell command, prints an error and returns false if it fails
static bool runCmd(const char* cmd) {
    if (std::system(cmd) != 0) {
        std::cerr << redText("Error: Command Failed: ") << cmd << "\n";
        return false;
    }
    return true;
}

// Tests Lexer, prints each line lexed
static int lexerTest() {
    // Open for reading
    std::ifstream lexerTest("../tests/lexer-tests.txt");

    // Check if file opened successfully
    if (!lexerTest.is_open()) {
        std::cerr << "Error: Could not open lexer test file." << std::endl;
        return 1;
    }

    std::string line;
    while (std::getline(lexerTest, line)) {
        auto tokenized = Lexer::tokenize(line);

        std::vector<Token> lineTokenVec = tokenized.first;
        std::cout << line << std::endl;
        for (const Token& token : lineTokenVec) {
            std::cout << token.mValue << " (" << typeName(token.mType) << "), ";
        }

        for (std::string& error : tokenized.second) {
            std::cerr << "\n" << redText(error);
        }

        std::cout << std::endl << std::endl;
    }

    // Close the file
    lexerTest.close();
    return 0;
}

// prints text line for parserTest
static void printLine(size_t spaces, const std::string& text) {
    std::cout << "\n" << std::string(spaces, ' ') << text;
}

// prints tree generated by parser sideways
static void printSideways(const Node* node, size_t spaces) {
    if (!node) return;
    spaces += 5;

    auto* binary = dynamic_cast<const BinaryOperation*>(node);
    auto* negate = dynamic_cast<const Negate*>(node);
    auto* function = dynamic_cast<const Function*>(node);
    auto* number = dynamic_cast<const Number*>(node);
    auto* identifier = dynamic_cast<const Identifier*>(node);
    auto* constant = dynamic_cast<const Constant*>(node);
    auto* string = dynamic_cast<const String*>(node);

    if (binary) {
        printSideways(binary->right.get(), spaces);
        printLine(spaces, binary->token.mValue);
        printSideways(binary->left.get(), spaces);
    } else if (negate) {
        printSideways(negate->operand.get(), spaces);
        printLine(spaces, "-");
    } else if (function) {
        for (size_t i = function->arguments.size(); i-- > 0;)   // last argument first, so it prints on top
            printSideways(function->arguments[i].get(), spaces);
        printLine(spaces, function->functionToken.mValue);
    } else if (number) {
        printLine(spaces, number->token.mValue);
    } else if (identifier) {
        printLine(spaces, identifier->token.mValue);
    } else if (constant) {
        printLine(spaces, constant->token.mValue);
    } else if (string) {
        printLine(spaces, "\"" + string->token.mValue + "\"");
    }
}

static int parserTest() {

    std::ifstream parserTest("../tests/parser-tests.txt");

    // Check if file opened successfully
    if (!parserTest.is_open()) {
        std::cerr << "Error: Could not open parser test file." << std::endl;
        return 1;
    }

    std::string line;
    while (std::getline(parserTest, line)) {

        Parser parser(Lexer::tokenize(line).first);
        std::cout << line << std::endl;

        if (parser.parse() == 0) {
            printSideways(parser.getResultTree(), 0);
            std::cout << "\n\n";
        } else {
            std::cout << redText(parser.getErrorMessage()) << "\n\n";
        }
    }

    return 0;
}

